CREATE OR REPLACE VIEW ASSESSMENT.PUBLIC.MARKETING AS
SELECT
    LMN.VENDOR_ID,
    LMN.ADVERTISER,
    LMN.MI_CAMPAIGN_NAME,
    LMN.MEDIA_SUBTYPE,
    LMN.PLAN_LABEL,
    LMN.AUDIENCE,
    LMN.FLIGHT_LABEL,
    LMN.SITE_NAME,
    LMN.DEVICE,
    LMN.CREATIVE_NAME,
    VOD.DAY,
    VOD.SITE_NAME AS VOD_SITE_NAME,
    VOD.DEVICE AS VOD_DEVICE,
    VOD.CREATIVE_NAME AS VOD_CREATIVE_NAME,
    VOD.IMPRESSIONS,
    VOD.CLICKS,
    VOD.SPEND,
    FEE.FEE
FROM ASSESSMENT.TRF.TRF_LUMINA_PLAN LMN
LEFT JOIN ASSESSMENT.TRF.TRF_VOD_PLATFORM VOD
ON LMN.VENDOR_ID = VOD.VENDOR_ID
LEFT JOIN ASSESSMENT.TRF.TRF_ADVERTISER_FEE FEE
ON LMN.ADVERTISER = FEE.ADVERTISER;
