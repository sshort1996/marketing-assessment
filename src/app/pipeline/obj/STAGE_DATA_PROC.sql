CREATE OR REPLACE PROCEDURE ASSESSMENT.RAW.LOAD_RAW_DATA()
  RETURNS STRING
  LANGUAGE SQL
AS
$$
BEGIN
  -- Load RAW_ADVERTISER_FEE
  COPY INTO RAW_ADVERTISER_FEE
  FROM @STAGE_RAW_DATA/advertiser_fee.csv.gz
  FILE_FORMAT = (FORMAT_NAME = 'FILE_FORMAT_CSV');

  -- Load RAW_LUMINA_PLAN
  COPY INTO RAW_LUMINA_PLAN
  FROM @STAGE_RAW_DATA/lumina_plan_information3.csv.gz
  FILE_FORMAT = (FORMAT_NAME = 'FILE_FORMAT_CSV');

  -- Load RAW_VOD_PLATFORM
  COPY INTO RAW_VOD_PLATFORM
  FROM @STAGE_RAW_DATA/vod_platform4.csv.gz
  FILE_FORMAT = (FORMAT_NAME = 'FILE_FORMAT_CSV');

  RETURN 'Data loaded successfully';
END;
$$;
